#!/usr/bin/env python3
"""Turn a CVA5 ELF into a C word array the Zynq PS can write into main memory.

    elf-to-c-array.py <cross-prefix> <elf> <out.c>

Emits:
    const uint32_t cva5_image[] = { 0x..., ... };
    const uint32_t cva5_image_words = N;

examples/ps/cva5_load.c consumes these; examples/ps/cva5_image.h declares them.

This is the PS's counterpart to elf-to-load-tcl.py, which does the same job for
OpenOCD, and the two agree on the one assumption that makes both trivial:
examples/sw/fpga_link.ld puts the whole program in one region at RAM_BASE, so
`objcopy -O binary` is the image and it is written at offset zero. Neither tool
parses an ELF.
"""
import subprocess
import sys


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    cross, elf, out = sys.argv[1], sys.argv[2], sys.argv[3]

    raw = elf + ".bin"
    subprocess.run([cross + "objcopy", "-O", "binary", elf, raw], check=True)
    with open(raw, "rb") as f:
        data = f.read()

    # Pad to a word. A trailing partial word can only be in .data or padding --
    # the linker aligns .text -- and the core reads it as a word either way.
    if len(data) % 4:
        data += b"\0" * (4 - len(data) % 4)
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]

    with open(out, "w") as f:
        f.write("/* Generated by tools/elf-to-c-array.py from %s -- do not edit.\n"
                " * Regenerate with: make -C examples/sw ps-image\n */\n"
                % elf)
        f.write('#include "cva5_image.h"\n\n')
        f.write("const uint32_t cva5_image[] = {\n")
        for i in range(0, len(words), 8):
            f.write("    " + " ".join("0x%08x," % w for w in words[i:i + 8]) + "\n")
        f.write("};\n\n")
        f.write("const uint32_t cva5_image_words = %d;\n" % len(words))

    print("%s: %d words (%d bytes)" % (out, len(words), len(data)))


if __name__ == "__main__":
    main()
