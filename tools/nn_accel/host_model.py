"""
host_model.py -- compile the accelerator's own generated C++ for the host,
and check it against what the board produced.

This is the gate for modelling the accelerator in QEMU. The plan there is
not to write a model of the network: hls4ml already emits one, and it is
the bit-accurate C++ that Vitis HLS turns into the RTL. If that code
compiles and runs outside Vitis then the QEMU device never has to know
anything about the network -- it loads whatever `make ip` last generated,
and the model regenerates whenever the model does. If it does not compile,
the QEMU plan needs rethinking before two days go into it rather than
after.

So this script answers one question: does the generated firmware build
with a plain g++ and produce the numbers the hardware produced?

One wrinkle this turned up, which matters for the QEMU device later:
compiled without `__SYNTHESIS__`, nnet_utils ignores the weight arrays in
`weights/*.h` and reloads them from `weights/*.txt` at run time, relative
to the working directory. Fine here, where the binary can be run from
inside the project. A `.so` that QEMU loads cannot rely on that, so the
build rule for it will need either the text files installed beside it or
the loading disabled -- a decision to make when the device is written,
not a surprise to meet then.

It is useful even if QEMU never happens. examples/sw/cifar.c's software
reference is int32 Q9 and the hardware truncates to ap_fixed<14,5> at
every layer, which is where the ~20% difference in logit magnitude comes
from. The thing built here has the hardware's arithmetic exactly, so it
can say which of the two a disagreement belongs to.

Nothing here needs Vitis, a licence, or a board. It does need the project
`make -C tools/nn_accel ip` generated, and the headers `make headers`
wrote, because the images it checks against are the ones the board ran.

Usage:
    python3 tools/nn_accel/host_model.py                 # build and check
    python3 tools/nn_accel/host_model.py --dir sw_12_5_rf4
    python3 tools/nn_accel/host_model.py --keep          # leave the sources

SPDX-License-Identifier: Apache-2.0
"""

import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))

# What the board produced, from the run recorded in
# docs/nn_accelerator/README.md: eight CIFAR images, frog and ship, the
# result word's two 14-bit lanes sign-extended. Hardware and the PS demo
# both give these, which is why they are worth comparing against.
BOARD = [(929, -626), (1278, -1160), (575, -198), (1237, -1307),
         (-1331, 1786), (-1538, 1966), (-461, 801), (-1542, 1806)]

SO_TAIL = r'''
/* The .so QEMU loads.
 *
 * __SYNTHESIS__ would have compiled the weights in and removed all file
 * I/O, but nnet_dense_latency.h does not build under it. So the weights
 * still come from weights/*.txt at run time, by a path relative to the
 * working directory -- and a QEMU process has no business having its
 * working directory anywhere in particular.
 *
 * Resolved once, at dlopen, and never again: chdir to the firmware
 * directory baked in at build time, run one inference on a zero image to
 * force nnet_utils' static loads, chdir back. The window is a few
 * milliseconds during device realize, before QEMU is doing anything else,
 * and after it the model touches no file for the life of the process.
 */
#include <unistd.h>

__attribute__((constructor))
static void cva5_accel_preload(void) {
    char cwd[4096];
    unsigned char zero[%(BYTES)d];
    int i;

    for (i = 0; i < %(BYTES)d; i++) zero[i] = 0;
    if (!getcwd(cwd, sizeof cwd)) return;
    if (chdir(FIRMWARE_DIR) != 0) {
        fprintf(stderr, "cva5_accel_model: cannot reach %%s -- the weights "
                        "will not load\n", FIRMWARE_DIR);
        return;
    }
    (void)cva5_accel_infer(zero);
    if (chdir(cwd) != 0)
        fprintf(stderr, "cva5_accel_model: could not restore the working "
                        "directory\n");
}
'''

SHIM = r'''
/* Generated by tools/nn_accel/host_model.py -- not in git.
 *
 * The accelerator's data path, in the words the hardware uses. One pixel
 * is one beat of input_t; one inference is one beat of result_t, which
 * holds both logits. The packing matches cva5_accel_axi's register: each
 * element's bits in the low part of a 16-bit lane, element 0 low.
 */
#include <cstdint>
#include <cstdio>
#include "cnn.h"

extern "C" uint32_t cva5_accel_infer(const unsigned char *img) {
    hls::stream<input_t>  in_s;
    hls::stream<result_t> out_s;
    int p, c;

    /* Four bytes a pixel, R G B and a pad byte the lane select drops.
     * ap_ufixed<8,0> means the byte IS the fixed-point value, so the raw
     * bits go straight in with no conversion -- the same claim the
     * hardware rests on. */
    for (p = 0; p < %(PIXELS)d; p++) {
        input_t v;
        for (c = 0; c < 3; c++)
            v[c].range() = img[p * 4 + c];
        in_s.write(v);
    }

    cnn(in_s, out_s);

    result_t r = out_s.read();
    uint32_t lo = (uint32_t)r[0].range().to_uint() & 0x3FFFu;
    uint32_t hi = (uint32_t)r[1].range().to_uint() & 0x3FFFu;
    return lo | (hi << 16);
}

static int sx(uint32_t lane) {          /* sign-extend from bit 13 */
    int v = (int)(lane & 0x3FFFu);
    return (v & 0x2000) ? v - 0x4000 : v;
}

extern const unsigned char HOST_IMAGES[][%(BYTES)d];
extern const int HOST_N_IMAGES;

int main(void) {
    int k;
    for (k = 0; k < HOST_N_IMAGES; k++) {
        uint32_t w = cva5_accel_infer(HOST_IMAGES[k]);
        printf("%%d 0x%%08x %%d %%d\n", k, w, sx(w), sx(w >> 16));
    }
    return 0;
}
'''


def die(msg, hint=None):
    print(f"host_model: {msg}", file=sys.stderr)
    if hint:
        print(f"            {hint}", file=sys.stderr)
    sys.exit(1)


def check_types(firmware):
    """Refuse to build against a project whose ports are not what the
    hardware has. A mismatch here would produce a model that disagrees
    with the board for a reason that has nothing to do with QEMU."""
    src = open(os.path.join(firmware, "defines.h")).read()

    m = re.search(r"typedef\s+nnet::array<(.+?),\s*([\d\s*/]+)>\s+input_t", src)
    if not m:
        die("no input_t in defines.h -- is this an io_stream project?")
    in_t, in_n = m.group(1).strip(), eval(m.group(2))
    if in_t != "ap_ufixed<8,0>" or in_n != 3:
        die(f"input_t is nnet::array<{in_t}, {in_n}>, expected "
            "nnet::array<ap_ufixed<8,0>, 3>",
            "the 4-bytes-per-pixel data path assumes one byte per channel; "
            "see docs/nn_accelerator/README.md")

    m = re.search(r"typedef\s+nnet::array<(.+?),\s*([\d\s*/]+)>\s+result_t", src)
    if not m:
        die("no result_t in defines.h")
    out_t, out_n = m.group(1).strip(), eval(m.group(2))
    if out_n != 2:
        die(f"result_t holds {out_n} elements, expected 2",
            "the 32-bit result register packs exactly two logits")
    print(f"host_model: input nnet::array<{in_t}, {in_n}>, "
          f"result nnet::array<{out_t}, {out_n}>")
    return out_t


def read_images(path, nbytes):
    """Pull the image bytes out of the generated examples/sw/images.h. The
    same images the board classified, so the comparison is like for like."""
    src = open(path).read()
    m = re.search(r"IMAGES\s*\[\s*N_IMAGES\s*\]\s*\[\s*IMG_BYTES\s*\]\s*=\s*\{(.*)\};",
                  src, re.S)
    if not m:
        die(f"no IMAGES array in {path}",
            "run 'make -C tools/nn_accel headers'")
    body = m.group(1)
    imgs = [[int(v) for v in re.findall(r"-?\d+", blk)]
            for blk in re.findall(r"\{(.*?)\}", body, re.S)]
    bad = [i for i, im in enumerate(imgs) if len(im) != nbytes]
    if bad:
        die(f"image {bad[0]} has {len(imgs[bad[0]])} bytes, expected {nbytes}")
    return imgs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="sw_14_5_rf4",
                    help="the hls4ml project, relative to tools/nn_accel")
    ap.add_argument("--images", default=None,
                    help="default: examples/sw/images.h")
    ap.add_argument("--keep", action="store_true",
                    help="leave the generated sources in place")
    ap.add_argument("--try-synthesis", action="store_true",
                    help="re-test whether -D__SYNTHESIS__ builds; it does "
                         "not, and the .so does not need it")
    ap.add_argument("--so", metavar="PATH", default=None,
                    help="also build the shared library the QEMU device "
                         "loads, at PATH")
    args = ap.parse_args()

    proj = os.path.join(HERE, args.dir)
    firmware = os.path.join(proj, "firmware")
    if not os.path.isdir(firmware):
        die(f"no generated firmware at {firmware}",
            "run 'make -C tools/nn_accel ip' first")

    # hls4ml writes ap_types and nnet_utils into the project, so nothing
    # here reaches into the venv or into a Vitis install.
    aptypes = os.path.join(firmware, "ap_types")
    nnet = os.path.join(firmware, "nnet_utils")
    for d in (aptypes, nnet):
        if not os.path.isdir(d):
            die(f"{d} is missing",
                "hls4ml writes these beside the firmware; regenerate the "
                "project")

    check_types(firmware)

    images = args.images or os.path.join(REPO, "examples", "sw", "images.h")
    if not os.path.isfile(images):
        die(f"{images} does not exist", "run 'make -C tools/nn_accel headers'")
    imgs = read_images(images, 32 * 32 * 4)

    build = os.path.join(REPO, "build", "host_model")
    os.makedirs(build, exist_ok=True)

    with open(os.path.join(build, "shim.cpp"), "w") as f:
        f.write(SHIM % {"PIXELS": 32 * 32, "BYTES": 32 * 32 * 4})
    with open(os.path.join(build, "images.cpp"), "w") as f:
        f.write("/* Generated by host_model.py. */\n")
        # `extern` on the definition, not just on the declaration in the
        # shim: a const at namespace scope has INTERNAL linkage in C++, so
        # a plain `const int HOST_N_IMAGES = 8;` here is invisible to the
        # other translation unit. HOST_IMAGES escaped this only because it
        # already had a declaration above its definition.
        f.write(f"extern const int HOST_N_IMAGES;\n")
        f.write(f"const int HOST_N_IMAGES = {len(imgs)};\n")
        f.write(f"extern const unsigned char HOST_IMAGES[][{32*32*4}];\n")
        f.write(f"const unsigned char HOST_IMAGES[][{32*32*4}] = {{\n")
        for im in imgs:
            f.write("{" + ",".join(str(v) for v in im) + "},\n")
        f.write("};\n")

    def build_and_run(tag, extra, cwd):
        """One build of the generated firmware, and its eight answers."""
        exe = os.path.join(build, "host_model_" + tag)
        cmd = ["g++", "-O2", "-std=c++14", "-o", exe,
               os.path.join(build, "shim.cpp"),
               os.path.join(build, "images.cpp"),
               os.path.join(firmware, "cnn.cpp"),
               f"-I{firmware}", f"-I{aptypes}", f"-I{nnet}",
               # hls4ml's generated code is full of #pragma HLS, which g++
               # does not know and does not need to.
               "-Wno-unknown-pragmas"] + extra
        print(f"host_model: building [{tag}] " + " ".join(extra))
        c = subprocess.run(cmd, capture_output=True, text=True)
        if c.returncode != 0:
            return None, "\n".join(c.stderr.strip().splitlines()[-25:]), c.stderr
        x = subprocess.run([exe], capture_output=True, text=True, cwd=cwd)
        if x.returncode != 0:
            return None, x.stderr.strip(), None
        rows = []
        for line in x.stdout.strip().splitlines():
            k, w, l0, l1 = line.split()
            rows.append((int(k), w, int(l0), int(l1)))
        return rows, None, None

    cmd = ["g++", "-O2", "-std=c++14", "-o", os.path.join(build, "host_model"),
           os.path.join(build, "shim.cpp"), os.path.join(build, "images.cpp"),
           os.path.join(firmware, "cnn.cpp"),
           f"-I{firmware}", f"-I{aptypes}", f"-I{nnet}",
           "-Wno-unknown-pragmas"]
    print("host_model: " + " ".join(cmd[:4]) + " ...")
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        tail = "\n".join(r.stderr.strip().splitlines()[-25:])
        # A link error and a compile error are different answers and only
        # one of them is about hls4ml. If the firmware compiled and the
        # link failed, the generated C++ is fine and the fault is in this
        # script's glue -- say so rather than reporting the gate as failed.
        linkonly = ("undefined reference" in r.stderr
                    or "ld returned" in r.stderr) and "error:" not in r.stderr
        if linkonly:
            die("the firmware COMPILED and the link failed:\n" + tail,
                "that is this script's glue, not hls4ml -- the gate's "
                "question is answered yes")
        die("the generated firmware did not compile for the host:\n" + tail,
            "this is the answer the spike was for -- the QEMU plan rests on "
            "it building")

    # Run from inside the firmware directory.
    #
    # Compiled without __SYNTHESIS__, hls4ml's nnet_utils does not use the
    # weight arrays in weights/*.h at all -- it reloads them at run time
    # from weights/*.txt, by a path relative to the working directory.
    # Vitis HLS runs csim from inside the project and so never meets this.
    # Defining __SYNTHESIS__ would also fix it and is the wrong fix: it
    # tells nnet_utils it is being synthesised, which changes more than
    # the weight loading.
    wdir = os.path.join(firmware, "weights")
    ntxt = len([n for n in os.listdir(wdir) if n.endswith(".txt")]) \
        if os.path.isdir(wdir) else 0
    if ntxt == 0:
        die(f"no weights/*.txt in {wdir}",
            "hls4ml writes them beside weights/*.h; regenerate the project "
            "with 'make -C tools/nn_accel ip'")

    r = subprocess.run([os.path.join(build, "host_model")],
                       capture_output=True, text=True, cwd=firmware)
    if r.returncode != 0:
        die("it compiled but did not run:\n" + r.stderr.strip())

    print()
    print("  img  packed      host logits    board logits   match")
    bad = 0
    rows_txt = []
    for line in r.stdout.strip().splitlines():
        k, w, l0, l1 = line.split()
        k, l0, l1 = int(k), int(l0), int(l1)
        rows_txt.append((k, w, l0, l1))
        if k < len(BOARD):
            b0, b1 = BOARD[k]
            ok = (l0, l1) == (b0, b1)
            bad += 0 if ok else 1
            print(f"  {k:3d}  {w}  {l0:6d},{l1:<6d}  {b0:6d},{b1:<6d}  "
                  f"{'yes' if ok else 'NO'}")
        else:
            print(f"  {k:3d}  {w}  {l0:6d},{l1:<6d}  {'':13} -")

    print()
    if bad:
        print(f"host_model: {bad} of {len(BOARD)} images differ from the "
              "board.")
        print("  The firmware builds and runs, which is what the spike asked."
              " Differing")
        print("  numbers mean the project here is not the one in the"
              " bitstream -- a")
        print("  different model, precision or reuse factor -- not that the"
              " approach")
        print("  is wrong.")
    else:
        print("host_model: every image matches the board.")
        print("  The generated C++ is a bit-accurate model of the"
              " accelerator and")
        print("  needs no Vitis to run. The QEMU device can load this rather"
              " than")
        print("  implement a network of its own.")

    # ---- and the build the QEMU device will actually have to use -------
    #
    # A .so loaded by QEMU cannot depend on the working directory, so it
    # cannot reload weights from weights/*.txt. Defining __SYNTHESIS__
    # makes nnet_utils use the arrays compiled in from weights/*.h and do
    # no file I/O at all -- but it also tells nnet_utils it is being
    # synthesised, which changes what compiles. That has to be shown
    # equivalent rather than assumed, which is what this does: same
    # images, same comparison, and then the two builds against each other.
    print()
    if not args.try_synthesis:
        print("host_model: __SYNTHESIS__ is known not to build here "
              "(nnet_dense_latency.h,")
        print("  ap_fixed has no += against itself under it). The .so loads "
              "its weights")
        print("  at dlopen instead. --try-synthesis to re-test that.")
        syn, err = None, None
    else:
        syn, err, _ = build_and_run("synthesis", ["-D__SYNTHESIS__"], build)
    if syn is None and err is not None:
        print("host_model: the __SYNTHESIS__ build did not work:")
        print("  " + (err or "").replace("\n", "\n  "))
        print("  Not fatal. It means the .so the QEMU device loads will need")
        print("  weights/*.txt installed beside it and its own directory to")
        print("  run from, rather than having them compiled in.")
    else:
        differ = [k for (k, w, a, b), (_, w2, c, d) in zip(syn, rows_txt)
                  if (w, a, b) != (w2, c, d)]
        if differ:
            print(f"host_model: __SYNTHESIS__ differs on images {differ}.")
            print("  The run-time weight loading and the compiled-in arrays")
            print("  are not the same numbers, which is worth knowing before")
            print("  either is trusted. Use the .txt path for the .so.")
        else:
            print("host_model: __SYNTHESIS__ gives identical results, with no")
            print("  file I/O. That is how the QEMU device's .so gets built:")
            print("  weights compiled in, nothing relative to a working")
            print("  directory.")

    # ---- the shared library, if asked for --------------------------------
    if args.so:
        sopath = os.path.abspath(args.so)
        os.makedirs(os.path.dirname(sopath) or ".", exist_ok=True)
        with open(os.path.join(build, "solib.cpp"), "w") as f:
            # Substitute FIRST, then cut. Splitting the template and then
            # writing it leaves %(PIXELS)d in the C++ verbatim.
            body = SHIM % {"PIXELS": 32 * 32, "BYTES": 32 * 32 * 4}
            f.write(body.split("extern const unsigned char HOST_IMAGES")[0])
            f.write(SO_TAIL % {"BYTES": 32 * 32 * 4})
        cmd = ["g++", "-O2", "-std=c++14", "-shared", "-fPIC", "-o", sopath,
               os.path.join(build, "solib.cpp"),
               os.path.join(firmware, "cnn.cpp"),
               f"-I{firmware}", f"-I{aptypes}", f"-I{nnet}",
               "-Wno-unknown-pragmas",
               f'-DFIRMWARE_DIR="{firmware}"']
        c = subprocess.run(cmd, capture_output=True, text=True)
        if c.returncode != 0:
            die("the shared library did not build:\n"
                + "\n".join(c.stderr.strip().splitlines()[-20:]))
        print()
        print(f"host_model: wrote {sopath}")
        print(f"  weights resolved against {firmware} at dlopen")

        # Load it the way QEMU will -- dlopen from an unrelated working
        # directory -- and run image 0. This is the whole contract the
        # device depends on: the constructor finds the weights without a
        # cwd of its own, and cva5_accel_infer returns the board's word.
        # Checking it here rather than inside QEMU saves a long evening.
        import ctypes
        lib = ctypes.CDLL(sopath)
        lib.cva5_accel_infer.restype = ctypes.c_uint32
        lib.cva5_accel_infer.argtypes = [ctypes.POINTER(ctypes.c_ubyte)]
        buf = (ctypes.c_ubyte * (32 * 32 * 4))(*imgs[0])
        got = lib.cva5_accel_infer(buf)
        want = int(rows_txt[0][1], 16)
        print(f"  dlopen check: image 0 gives 0x{got:08x}, "
              f"wanted 0x{want:08x} -- {'ok' if got == want else 'WRONG'}")
        if got != want:
            die("the shared library does not reproduce the executable",
                "most likely the dlopen-time weight load did not happen; "
                "FIRMWARE_DIR is baked in at build time and must still "
                "exist when QEMU runs")

    if not args.keep:
        for n in ("shim.cpp", "images.cpp"):
            os.remove(os.path.join(build, n))


if __name__ == "__main__":
    main()
